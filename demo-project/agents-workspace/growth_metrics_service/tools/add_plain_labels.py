def main() -> None:
    path = CONFIG_DIR / "metric_dict.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    missing = []
    for m in data["metrics"]:
        plain = PLAIN.get(m["ref"])
        if plain:
            m["plain"] = plain
        else:
            missing.append(m["ref"])
    data["note"] = (
        "生成后此文件为唯一事实源，请直接编辑，不要再从 xlsx 覆盖生成。"
        "plain 是给老板/运营看的说法，改这里就能改 Agent 的措辞。"
    )
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"已补 plain：{len(data['metrics']) - len(missing)} / {len(data['metrics'])}")
    if missing:
        print("仍缺 plain：")
        for ref in missing:
            print(f"  {ref}")


if __name__ == "__main__":
    main()
