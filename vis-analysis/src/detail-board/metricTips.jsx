export function MetricLabel({ children, tip, book }) {
  const key = tip || (typeof children === "string" ? children : "")
  const item = (book && book[key]) || TIPS[key]
  const help = (
    <span className="db-metric-label">
      {children}
      {item ? (
        <Tooltip
          placement="topLeft"
          trigger={["hover", "focus"]}
          mouseEnterDelay={0.1}
          autoAdjustOverflow
          styles={{ container: { maxWidth: 320 } }}
          title={(
            <div className="db-tip">
              <p><b>含义</b>{item.meaning}</p>
              <p><b>口径</b>{item.scope}</p>
            </div>
          )}
        >
          <span
            className="db-metric-help"
            role="button"
            tabIndex={0}
            aria-label={`${children}的含义和口径`}
            onMouseDown={(event) => event.stopPropagation()}
            onClick={(event) => event.stopPropagation()}
            onKeyDown={(event) => event.stopPropagation()}
          >
            <QuestionCircleOutlined />
          </span>
        </Tooltip>
      ) : null}
    </span>
  )
  return help
}
